import { DockerfileGenerateOptions } from './dockerfile.types';

export function generateReactDockerfile(
  options: DockerfileGenerateOptions,
): string {
  const port = options.port ?? 80;
  return [
    'FROM node:20-alpine AS builder',
    'WORKDIR /app',
    'COPY package*.json ./',
    'COPY pnpm-lock.yaml* yarn.lock* ./',
    'RUN if [ -f pnpm-lock.yaml ]; then corepack enable && pnpm install --frozen-lockfile; elif [ -f yarn.lock ]; then yarn install --frozen-lockfile; elif [ -f package-lock.json ]; then npm ci; else npm install; fi',
    'COPY . .',
    'RUN if [ -f pnpm-lock.yaml ]; then pnpm run build; elif [ -f yarn.lock ]; then yarn build; else npm run build; fi && \\',
    '    if [ -d dist ]; then cp -R dist /tmp/web; elif [ -d build ]; then cp -R build /tmp/web; elif [ -d out ]; then cp -R out /tmp/web; elif [ -d .output/public ]; then cp -R .output/public /tmp/web; else mkdir -p /tmp/web && cp -R . /tmp/web; fi',
    '',
    'FROM nginx:alpine',
    "RUN printf 'server {\\n\\",
    '    listen 80;\\n\\',
    '    server_name _;\\n\\',
    '    root /usr/share/nginx/html;\\n\\',
    '    index index.html index.htm;\\n\\',
    '\\n\\',
    '    gzip on;\\n\\',
    '    gzip_vary on;\\n\\',
    '    gzip_proxied any;\\n\\',
    '    gzip_comp_level 6;\\n\\',
    '    gzip_types text/plain text/css text/xml application/json application/javascript application/rss+xml application/atom+xml image/svg+xml;\\n\\',
    '\\n\\',
    '    location / {\\n\\',
    '        try_files $uri $uri/ /index.html;\\n\\',
    '    }\\n\\',
    '\\n\\',
    '    location ~* \\\\.(?:css|js|woff2?|svg|gif|png|jpe?g|webp|avif|ico)$ {\\n\\',
    '        expires 1y;\\n\\',
    '        add_header Cache-Control "public, max-age=31536000, immutable";\\n\\',
    '        access_log off;\\n\\',
    '        try_files $uri =404;\\n\\',
    '    }\\n\\',
    '\\n\\',
    '    location ~* \\\\.(?:html|htm)$ {\\n\\',
    '        add_header Cache-Control "no-cache, no-store, must-revalidate";\\n\\',
    '        expires 0;\\n\\',
    '    }\\n\\',
    "}\\n' > /etc/nginx/conf.d/default.conf",
    '',
    'COPY --from=builder /tmp/web /usr/share/nginx/html',
    `EXPOSE ${port}`,
    `HEALTHCHECK --interval=30s --timeout=5s --start-period=5s CMD wget -qO- http://127.0.0.1:${port}/ >/dev/null 2>&1 || exit 1`,
  ].join('\n');
}
